// Builds the flag set for World Flags (web/flags/): copies the country flags from the flag-icons package
// (MIT, https://github.com/lipis/flag-icons) and writes web/flags/data.js with each country's name,
// continent, main colours and a complexity score (how detailed the flag drawing is).
//   npm pack flag-icons@7.2.3 && tar xzf flag-icons-7.2.3.tgz
//   node tools/build-flags.mjs package
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const src = process.argv[2];
if (!src) throw new Error('Usage: node tools/build-flags.mjs <flag-icons package folder>');
const out = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'web', 'flags');

// The 193 UN member states plus Vatican City, Palestine, Kosovo and Taiwan.
const SOVEREIGN = `af al dz ad ao ag ar am au at az bs bh bd bb by be bz bj bt bo ba bw br bn bg bf bi cv kh cm ca cf td cl cn
co km cg cd cr ci hr cu cy cz dk dj dm do ec eg sv gq er ee sz et fj fi fr ga gm ge de gh gr gd gt gn gw gy ht hn hu is in id
ir iq ie il it jm jp jo kz ke ki kp kr kw kg la lv lb ls lr ly li lt lu mg mw my mv ml mt mh mr mu mx fm md mc mn me ma mz mm
na nr np nl nz ni ne ng mk no om pk pw pa pg py pe ph pl pt qa ro ru rw kn lc vc ws sm st sa sn rs sc sl sg sk si sb so za ss
es lk sd sr se ch sy tj tz th tl tg to tt tn tr tm tv ug ua ae gb us uy uz vu ve vn ye zm zw va ps xk tw`.split(/\s+/);

// Short, familiar names instead of the formal ones in country.json.
const NAMES = {
  bo: 'Bolivia', ir: 'Iran', kp: 'North Korea', kr: 'South Korea', la: 'Laos', md: 'Moldova', fm: 'Micronesia',
  ru: 'Russia', sy: 'Syria', tz: 'Tanzania', ve: 'Venezuela', vn: 'Vietnam', bn: 'Brunei', cd: 'DR Congo',
  cg: 'Congo', ci: "Côte d'Ivoire", cz: 'Czechia', gb: 'United Kingdom', us: 'United States', va: 'Vatican City',
  ps: 'Palestine', xk: 'Kosovo', tw: 'Taiwan', mk: 'North Macedonia', sz: 'Eswatini', cv: 'Cape Verde',
  tl: 'Timor-Leste', kn: 'Saint Kitts and Nevis', vc: 'Saint Vincent', lc: 'Saint Lucia', st: 'São Tomé and Príncipe',
  ae: 'United Arab Emirates', mm: 'Myanmar', bs: 'Bahamas', gm: 'Gambia',
};

// Flags nearly everyone knows: level 1 uses these.
const FAMOUS = `us gb fr de it es jp cn br ca mx in ru au kr ar pt nl se ch tr gr eg za ng ie be no dk fi pl
ua sa il ke jm ca nz th`.split(/\s+/);

const info = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(src, 'country.json'), 'utf8')).map(c => [c.code, c]));
fs.mkdirSync(path.join(out, 'img'), { recursive: true });

const rows = [];
for (const code of SOVEREIGN) {
  const file = path.join(src, 'flags', '4x3', code + '.svg');
  const svg = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(path.join(out, 'img', code + '.svg'), svg);
  // Complexity: compressed size of the drawing, plus the number of shapes and colours.
  const gz = zlib.gzipSync(svg).length;
  const shapes = (svg.match(/<(path|circle|ellipse|polygon|rect|use)\b/g) || []).length;
  const colors = [...new Set((svg.match(/#[0-9a-f]{3,6}\b/gi) || []).map(norm))];
  const score = Math.log2(gz) * 10 + Math.min(shapes, 200) / 10 + colors.length * 2;
  rows.push({ c: code, n: NAMES[code] || info[code]?.name || code, r: info[code]?.continent || '', k: colors.slice(0, 6), s: Math.round(score) });
}

// Level 1 = famous flags; the rest are split by complexity into levels 2 to 5.
const rest = rows.filter(r => !FAMOUS.includes(r.c)).sort((a, b) => a.s - b.s);
for (const r of rows) if (FAMOUS.includes(r.c)) r.l = 1;
rest.forEach((r, i) => { r.l = 2 + Math.floor(i * 4 / rest.length); });
rows.sort((a, b) => a.n.localeCompare(b.n));

fs.writeFileSync(path.join(out, 'data.js'), '// Generated by tools/build-flags.mjs. c=code n=name r=continent k=colours s=complexity l=level\n' +
  'window.FLAGS = ' + JSON.stringify(rows).replace(/\},\{/g, '},\n{') + ';\n');
fs.copyFileSync(path.join(src, 'LICENSE'), path.join(out, 'img', 'LICENSE.txt'));
const per = [1, 2, 3, 4, 5].map(l => rows.filter(r => r.l === l).length);
console.log(`${rows.length} flags, per level: ${per.join(' / ')}`);

function norm(h) {
  h = h.toLowerCase();
  return h.length === 4 ? '#' + h[1] + h[1] + h[2] + h[2] + h[3] + h[3] : h;
}
